/**
 * AIMS project schema (versioned).
 *
 * This is the single source of truth for everything a project can contain.
 * AI-generated arrangements, imported projects and autosaves are all validated
 * against these schemas before they reach the audio engine or the editor.
 *
 * Time is measured in BEATS (quarter notes) unless a field says otherwise.
 */
import { z } from 'zod';

export const PROJECT_FORMAT = 'aims-project';
export const PROJECT_VERSION = 1;

const num = (min: number, max: number) => z.number().finite().min(min).max(max);

export const WaveSchema = z.enum(['sine', 'square', 'sawtooth', 'triangle']);
export type Wave = z.infer<typeof WaveSchema>;

export const EnvelopeSchema = z.object({
  attack: num(0, 20),
  decay: num(0, 20),
  sustain: num(0, 1),
  release: num(0, 30),
});
export type Envelope = z.infer<typeof EnvelopeSchema>;

export const OscSchema = z.object({
  wave: WaveSchema,
  octave: num(-3, 3),
  semi: num(-24, 24),
  detune: num(-100, 100),
  level: num(0, 1),
});

/** Parameter block shared by all synthesized instrument engines. Each engine uses the subset it needs. */
export const SynthParamsSchema = z.object({
  osc1: OscSchema,
  osc2: OscSchema,
  subLevel: num(0, 1),
  noiseLevel: num(0, 1),
  unison: num(1, 7),
  unisonSpread: num(0, 100),
  filter: z.object({
    type: z.enum(['lowpass', 'highpass', 'bandpass']),
    cutoff: num(20, 20000),
    resonance: num(0.1, 30),
    envAmount: num(-6, 8), // octaves
    keyTrack: num(0, 1),
  }),
  ampEnv: EnvelopeSchema,
  filterEnv: EnvelopeSchema,
  vibrato: z.object({ rate: num(0, 20), depth: num(0, 200), delay: num(0, 5) }),
  lfo: z.object({ rate: num(0, 30), toCutoff: num(0, 4), toAmp: num(0, 1), wave: WaveSchema }),
  fm: z.object({ ratio: num(0.25, 16), index: num(0, 20), indexDecay: num(0.01, 10), modWave: WaveSchema }),
  drawbars: z.array(num(0, 8)).length(9),
  pluck: z.object({ damping: num(0, 1), brightness: num(0, 1), body: num(0, 1) }),
  glide: num(0, 2),
  gain: num(-48, 12), // dB
  transpose: num(-48, 48),
  fine: num(-100, 100),
  velocitySens: num(0, 1),
  expression: num(0, 1),
  pan: num(-1, 1),
  maxVoices: num(1, 128),
});
export type SynthParams = z.infer<typeof SynthParamsSchema>;

export const DrumPieceSchema = z.object({
  tune: num(-24, 24),
  decay: num(0.1, 4),
  level: num(0, 2),
  pan: num(-1, 1),
  sampleAssetId: z.string().nullable(),
});
export type DrumPiece = z.infer<typeof DrumPieceSchema>;

export const DrumKitSchema = z.enum(['electronic', '808', 'acoustic', 'orchestral', 'lofi', 'trap', 'rock']);
export type DrumKitName = z.infer<typeof DrumKitSchema>;

export const SampleZoneSchema = z.object({
  assetId: z.string(),
  name: z.string(),
  rootPitch: num(0, 127),
  loPitch: num(0, 127),
  hiPitch: num(0, 127),
  loVel: num(0, 1),
  hiVel: num(0, 1),
  gain: num(-48, 12),
  loop: z.boolean(),
});
export type SampleZone = z.infer<typeof SampleZoneSchema>;

export const InstrumentKindSchema = z.enum(['subtractive', 'fm', 'organ', 'pluck', 'drumkit', 'sampler', 'none']);
export type InstrumentKind = z.infer<typeof InstrumentKindSchema>;

export const InstrumentSchema = z.object({
  kind: InstrumentKindSchema,
  preset: z.string(),
  /** 'synth' = generated by synthesis in the browser; 'sampled' = plays recorded audio samples supplied by the user. */
  source: z.enum(['synth', 'sampled']),
  params: SynthParamsSchema,
  kit: DrumKitSchema,
  pieces: z.record(z.string(), DrumPieceSchema),
  zones: z.array(SampleZoneSchema),
});
export type Instrument = z.infer<typeof InstrumentSchema>;

export const EffectTypeSchema = z.enum([
  'eq', 'compressor', 'limiter', 'reverb', 'delay', 'chorus', 'flanger', 'phaser',
  'distortion', 'saturation', 'filter', 'width', 'ducking', 'gate', 'bitcrush', 'gain',
]);
export type EffectType = z.infer<typeof EffectTypeSchema>;

export const EffectSchema = z.object({
  id: z.string(),
  type: EffectTypeSchema,
  enabled: z.boolean(),
  params: z.record(z.string(), z.union([z.number().finite(), z.string(), z.boolean()])),
});
export type Effect = z.infer<typeof EffectSchema>;

export const NoteSchema = z.object({
  id: z.string(),
  pitch: z.number().int().min(0).max(127),
  start: num(0, 100000),
  duration: num(1 / 256, 10000),
  velocity: num(0, 1),
  lyric: z.string().optional(),
});
export type Note = z.infer<typeof NoteSchema>;

export const AudioClipDataSchema = z.object({
  assetId: z.string(),
  gain: num(-60, 24),
  fadeIn: num(0, 600), // seconds
  fadeOut: num(0, 600),
  playbackRate: num(0.25, 4),
  startSec: num(0, 36000), // offset into the source file
  reverse: z.boolean(),
});
export type AudioClipData = z.infer<typeof AudioClipDataSchema>;

export const ClipSchema = z.object({
  id: z.string(),
  kind: z.enum(['midi', 'audio']),
  name: z.string(),
  start: num(0, 100000),
  length: num(1 / 64, 100000),
  /** Content offset (beats) – trimming the left edge increases this. */
  offset: num(0, 100000),
  loop: z.boolean(),
  /** Length of one loop iteration of the content (beats). */
  contentLength: num(1 / 64, 100000),
  color: z.string().nullable(),
  notes: z.array(NoteSchema),
  swing: num(0, 1),
  muted: z.boolean(),
  sectionId: z.string().nullable(),
  audio: AudioClipDataSchema.nullable(),
});
export type Clip = z.infer<typeof ClipSchema>;

export const AutomationPointSchema = z.object({ beat: num(0, 100000), value: z.number().finite() });
export const AutomationLaneSchema = z.object({
  id: z.string(),
  /** 'volume' | 'pan' | 'inst.cutoff' | 'inst.resonance' | 'fx.<effectId>.<param>' | 'send.<returnId>' */
  target: z.string(),
  enabled: z.boolean(),
  points: z.array(AutomationPointSchema),
});
export type AutomationLane = z.infer<typeof AutomationLaneSchema>;
export type AutomationPoint = z.infer<typeof AutomationPointSchema>;

export const TrackRoleSchema = z.enum([
  'melody', 'countermelody', 'harmony', 'chords', 'pad', 'bass', 'arp', 'drums', 'percussion',
  'strings', 'brass', 'woodwinds', 'ostinato', 'fx', 'vocal', 'backing-vocal', 'audio', 'other',
]);
export type TrackRole = z.infer<typeof TrackRoleSchema>;

export const SendSchema = z.object({ returnId: z.string(), level: num(0, 1) });

export const TrackSchema = z.object({
  id: z.string(),
  name: z.string(),
  type: z.enum(['instrument', 'drums', 'audio']),
  role: TrackRoleSchema,
  color: z.string(),
  instrument: InstrumentSchema,
  volume: num(-70, 12), // dB
  pan: num(-1, 1),
  mute: z.boolean(),
  solo: z.boolean(),
  armed: z.boolean(),
  monitor: z.boolean(),
  effects: z.array(EffectSchema),
  sends: z.array(SendSchema),
  output: z.string(), // 'master' or a return bus id
  groupId: z.string().nullable(),
  clips: z.array(ClipSchema),
  automation: z.array(AutomationLaneSchema),
  height: num(28, 400),
  /** Accompaniment pattern used by the composer when (re)generating this part (e.g. 'arp', 'strum'). */
  pattern: z.string().nullable().default(null),
});
export type Track = z.infer<typeof TrackSchema>;

export const ReturnBusSchema = z.object({
  id: z.string(),
  name: z.string(),
  color: z.string(),
  volume: num(-70, 12),
  mute: z.boolean(),
  effects: z.array(EffectSchema),
});
export type ReturnBus = z.infer<typeof ReturnBusSchema>;

export const GroupSchema = z.object({ id: z.string(), name: z.string(), color: z.string(), collapsed: z.boolean() });
export type TrackGroup = z.infer<typeof GroupSchema>;

export const SectionKindSchema = z.enum([
  'intro', 'verse', 'prechorus', 'chorus', 'postchorus', 'bridge', 'breakdown', 'buildup', 'drop',
  'solo', 'interlude', 'outro', 'theme', 'development', 'climax', 'coda', 'custom',
]);
export type SectionKind = z.infer<typeof SectionKindSchema>;

export const SectionSchema = z.object({
  id: z.string(),
  name: z.string(),
  kind: SectionKindSchema,
  start: num(0, 100000),
  length: num(1, 100000),
  energy: num(0, 1),
  /** Semitones relative to the project key (modulation / key change). */
  transpose: z.number().int().min(-12).max(12).default(0),
});
export type Section = z.infer<typeof SectionSchema>;

export const ChordEventSchema = z.object({
  start: num(0, 100000),
  length: num(1 / 16, 10000),
  root: z.number().int().min(0).max(11),
  quality: z.string(),
  bass: z.number().int().min(0).max(11).nullable(),
  symbol: z.string(),
});
export type ChordEvent = z.infer<typeof ChordEventSchema>;

export const MarkerSchema = z.object({ id: z.string(), beat: num(0, 100000), name: z.string(), color: z.string() });
export type Marker = z.infer<typeof MarkerSchema>;

export const TempoChangeSchema = z.object({ beat: num(0, 100000), bpm: num(20, 400) });
export type TempoChange = z.infer<typeof TempoChangeSchema>;
export const SignatureChangeSchema = z.object({
  beat: num(0, 100000),
  numerator: z.number().int().min(1).max(32),
  denominator: z.union([z.literal(2), z.literal(4), z.literal(8), z.literal(16)]),
});
export type SignatureChange = z.infer<typeof SignatureChangeSchema>;

export const ModeSchema = z.enum([
  'major', 'minor', 'harmonicMinor', 'melodicMinor', 'dorian', 'phrygian', 'lydian', 'mixolydian',
  'locrian', 'pentatonicMajor', 'pentatonicMinor', 'blues', 'chromatic',
]);
export type ModeName = z.infer<typeof ModeSchema>;

export const GenerationSettingsSchema = z.object({
  prompt: z.string(),
  genre: z.string(),
  mood: z.string(),
  durationSec: num(10, 1200),
  bpm: num(0, 400), // 0 = auto
  key: z.string(), // 'auto' or e.g. 'D minor'
  vocals: z.enum(['none', 'recorded', 'ai']),
  complexity: num(0, 1),
  energy: num(0, 1),
  creativity: num(0, 1),
  instrumentation: z.string(), // 'auto' or comma separated
  structure: z.string(), // 'auto' or comma separated section kinds
  seed: z.number().int(),
  engine: z.enum(['local', 'claude']),
});
export type GenerationSettings = z.infer<typeof GenerationSettingsSchema>;

export const ArrangementStyleSchema = z.object({
  genre: z.string(),
  mood: z.string(),
  drums: z.string(),
  bass: z.string(),
  swing: num(0, 1),
  melodyDensity: num(0, 1),
  syncopation: num(0, 1),
  complexity: num(0, 1),
  creativity: num(0, 1),
  seed: z.number().int(),
});
export type ArrangementStyle = z.infer<typeof ArrangementStyleSchema>;

export const LyricSectionSchema = z.object({ id: z.string(), label: z.string(), text: z.string(), sectionId: z.string().nullable() });
export type LyricSection = z.infer<typeof LyricSectionSchema>;

export const ProjectSchema = z.object({
  format: z.literal(PROJECT_FORMAT),
  version: z.literal(PROJECT_VERSION),
  id: z.string(),
  name: z.string(),
  createdAt: z.number(),
  updatedAt: z.number(),
  bpm: num(20, 400),
  tempoChanges: z.array(TempoChangeSchema),
  timeSignature: SignatureChangeSchema.omit({ beat: true }),
  signatureChanges: z.array(SignatureChangeSchema),
  key: z.object({ tonic: z.number().int().min(0).max(11), mode: ModeSchema }),
  sampleRate: z.union([z.literal(44100), z.literal(48000)]),
  tracks: z.array(TrackSchema),
  returns: z.array(ReturnBusSchema),
  groups: z.array(GroupSchema),
  master: z.object({ volume: num(-70, 12), effects: z.array(EffectSchema), preset: z.string() }),
  markers: z.array(MarkerSchema),
  sections: z.array(SectionSchema),
  chords: z.array(ChordEventSchema),
  loop: z.object({ enabled: z.boolean(), start: num(0, 100000), end: num(0, 100000) }),
  lyrics: z.object({
    sections: z.array(LyricSectionSchema),
    vocalStyle: z.object({ voice: z.enum(['any', 'male', 'female', 'choir']), delivery: z.string() }),
  }),
  generation: GenerationSettingsSchema.nullable(),
  /** Arrangement style knowledge kept so sections can be regenerated consistently. */
  style: ArrangementStyleSchema.nullable().default(null),
  metronome: z.object({ enabled: z.boolean(), countInBars: z.number().int().min(0).max(4), volume: num(0, 1) }),
  notes: z.string(),
});
export type Project = z.infer<typeof ProjectSchema>;
