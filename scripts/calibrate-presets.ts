/**
 * Dev tool: measures every preset at a reference performance and writes
 * src/model/presetTrim.ts so all presets sit at the same reference loudness.
 * Run: npx tsx scripts/calibrate-presets.ts [preset-id ...]  (no ids = all presets)
 */
import * as wa from 'node-web-audio-api';
for (const [k, v] of Object.entries(wa)) if (!(k in globalThis)) (globalThis as any)[k] = v;
import { writeFileSync } from 'node:fs';
import { newMidiClip, newNote, newProject, newTrack } from '../src/model/factory';
import { PRESETS } from '../src/model/presets';
import { PRESET_TRIM } from '../src/model/presetTrim';
import { renderProject } from '../src/audio/render';
import { analyze } from '../src/export/analysis';

const TARGET = -20; // dBFS RMS of the reference performance, pre-fader
(async () => {
  const only = process.argv.slice(2);
  const out: Record<string, number> = only.length ? { ...PRESET_TRIM } : {};
  for (const pr of PRESETS.filter((p) => !only.length || only.includes(p.id))) {
    const p = newProject();
    p.master.effects = [];
    p.bpm = 120;
    const t = newTrack({ preset: pr.id });
    t.volume = 0;
    t.sends = [];
    t.instrument.params.gain = pr.params.gain ?? -6; // untrimmed
    const notes = [];
    if (pr.kind === 'drumkit') {
      for (let b = 0; b < 8; b++) {
        notes.push(newNote(pr.kit === 'orchestral' ? 35 : 36, b, 0.25, 0.85));
        if (b % 2 === 1) notes.push(newNote(38, b, 0.25, 0.85));
        notes.push(newNote(42, b + 0.5, 0.1, 0.7));
      }
    } else {
      const mid = Math.round((pr.range[0] + pr.range[1]) / 2);
      const chordy = ['Keys', 'Pad', 'Strings', 'Organ', 'Guitar', 'Choir', 'Brass'].includes(pr.category) && !['trumpet', 'trombone', 'violins', 'cellos', 'vocal-guide'].includes(pr.id);
      const pitches = chordy ? [mid - 4, mid, mid + 3] : [mid];
      for (let b = 0; b < 8; b += 2) for (const x of pitches) notes.push(newNote(x + (b % 4 === 2 ? 2 : 0), b, 1.9, 0.8));
    }
    t.clips.push(newMidiClip(0, 8, notes));
    p.tracks.push(t);
    const buf = await renderProject(p, { get: () => undefined }, { sampleRate: 44100, OfflineCtx: (wa as any).OfflineAudioContext, tailSec: 0.2 });
    const a = analyze(buf);
    const trim = Math.max(-24, Math.min(24, Math.round((TARGET - a.rmsDb) * 2) / 2));
    out[pr.id] = trim;
    console.log(pr.id.padEnd(18), 'rms', a.rmsDb.toFixed(1).padStart(6), 'peak', a.peakDb.toFixed(1).padStart(6), '→ trim', trim);
  }
  writeFileSync('src/model/presetTrim.ts', `/** Generated by scripts/calibrate-presets.ts – per-preset gain trims (dB) to a common reference loudness. */\nexport const PRESET_TRIM: Record<string, number> = ${JSON.stringify(out, null, 2)};\n`);
})();
